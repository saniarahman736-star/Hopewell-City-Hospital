const mongoose=require("mongoose");
const prescriptionSchema=new mongoose.Schema(
    {
        patientId:{
            type:mongoose.Schema.Types.ObjectId,
            ref:"User",
            required:true
        },
        doctorId:{
            type:mongoose.Schema.Types.ObjectId,
            ref:"Doctor",
            required:true
        },
        appointmentId:{
            type:mongoose.Schema.Types.ObjectId,
            ref:"Appointment",
            required:true
        },
        diagnosis:{
            type:String,
            trim:true,
        },
        medicines:[
            {
                name:{
                    type:String,
                    required:true,
                    trim:true
                },
                dosage:{
                    type:String,
                    trim:true
                },
                frequency:{
                    type:String,
                    trim:true
                },
                duration:{
                    type:String,
                    trim:true,
                },
                instructions:{
                    type:String,
                    trim:true
                },
                timings:{
                    type:[String],
                    default:[]
                }
            },
        ],
        tests:{
            type:String,
            trim:true,
        },
        advice:{
            type:String,
            trim:true,
        },
        followUpDate:{
            type:String,
        },
    },
    {
        timestamps:true,
    }
);
module.exports=mongoose.model(
    "Prescription",prescriptionSchema
);